function c = okabe_ito(name)
%OKABE_ITO  色盲安全配色（Okabe-Ito 色板），黑白打印可配合线型区分
%   c = okabe_ito('blue'|'orange'|'green'|'vermillion'|'skyblue'|'purple')
persistent P
if isempty(P)
    P = struct( ...
        'blue',       [  0 114 178]/255, ...
        'orange',     [230 159   0]/255, ...
        'green',      [  0 158 115]/255, ...
        'vermillion', [213  94   0]/255, ...
        'skyblue',    [ 86 180 233]/255, ...
        'purple',     [204 121 167]/255);
end
c = P.(name);
end
